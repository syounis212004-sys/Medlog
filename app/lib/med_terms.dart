/// Best matches for what the user typed (prefix first, then contains).
List<MapEntry<String, String>> lookupTerms(String q) {
  final s = q.trim().toLowerCase();
  final all = {...kMedTermsExtra, ...kMedTerms};
  if (s.isEmpty) return (all.entries.toList()..sort((a, b) => a.key.compareTo(b.key)));
  final arabic = RegExp(r'[؀-ۿ]').hasMatch(s);
  final pre = <MapEntry<String, String>>[];
  final inn = <MapEntry<String, String>>[];
  for (final e in all.entries) {
    final hay = arabic ? e.value : e.key;
    if (hay.toLowerCase().startsWith(s)) {
      pre.add(e);
    } else if (hay.toLowerCase().contains(s)) {
      inn.add(e);
    }
  }
  int byKey(MapEntry<String, String> a, MapEntry<String, String> b) => a.key.compareTo(b.key);
  return [...(pre..sort(byKey)), ...(inn..sort(byKey))];
}
